const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../panorama/scripts/custom_game/zepractice/radio_filter.js'), 'utf8');
const label = { paneltype: 'Label', text: 'ZE 跑图主菜单', IsValid: () => true, Children: () => [] };
const menu = { paneltype: 'Panel', style: {}, IsValid: () => true, Children: () => [label] };
const background = { style: {} };
let alive = true;
let callback;
let inputVisible = false;
let closeCallback;
const commands = [];
const root = { IsValid: () => alive, BHasClass: (name) => name === 'ShowHudRadio' && inputVisible, FindChildTraverse: (name) => name === 'RadioPanel' ? menu : background };
vm.runInNewContext(source, { GameInterfaceAPI: { ConsoleCommand: (command) => commands.push(command) }, $: { GetContextPanel: () => root, Schedule: (delay, action) => {
    if (delay === 0.15) closeCallback = action;
    else { assert.equal(delay, 0.05); callback = action; }
} } });
assert.equal(menu.style.opacity, '1');
label.text = '__ZE_DYNAMIC_INPUT__';
callback();
assert.equal(menu.style.opacity, '0');
assert.equal(background.style.opacity, '0');
label.text = '个人辅助';
callback();
assert.equal(menu.style.opacity, '1');
assert.equal(background.style.opacity, '1');
inputVisible = true;
label.text = '__ZE_DYNAMIC_INPUT__';
callback();
inputVisible = false;
callback();
assert.equal(typeof closeCallback, 'function');
assert.equal(commands.length, 0);
closeCallback();
assert.deepEqual(commands, ['css_ze_ui_close']);
inputVisible = true;
callback();
inputVisible = false;
callback();
inputVisible = true;
closeCallback();
assert.equal(commands.length, 1);
label.text = 'ZE 主菜单';
callback();
closeCallback = null;
inputVisible = false;
callback();
assert.equal(closeCallback, null);
label.text = '__ZE_DYNAMIC_INPUT__';
inputVisible = true;
callback();
inputVisible = false;
callback();
alive = false;
closeCallback();
assert.equal(commands.length, 1);
const last = callback;
callback = null;
last();
assert.equal(callback, null);
console.log('RADIO_FILTER_TESTS 12/12 passed');
